# DATABASE

    # container of data
    # is an organised collection of related data so that it can be easily store,accessed and updated

# DBMS - DATABASE MANAGEMENT SYSTEM

    # software used to create store and manage database
    # eg: MYSQL,POSTGRES,MONGODB,ORACLE,SQLITE

# 2 TYPES OF DATABASE

    # RELATIONAL DB (SQL) - data is organised in the form of row and column (eg: MYSQL,POSTGRES,SQLITE)
    # NON-RELATIONAL DB(NON-SQL) - Data is organised in the form of documents,key-value,graphs (MONGODB)

# CRUD OPERATION - CREATE,READ,UPDATE,DELETE

# SQL - Structured Query Language - type of  programming language used to interact with relaional db

